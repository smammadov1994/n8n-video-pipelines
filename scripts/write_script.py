#!/usr/bin/env python3
"""Write our own UGC script + shot plan for one understood video.

    write_script.py <base64 of the video's JSON item>     # how the n8n workflow calls it
    write_script.py --json '{...}'

Input item: what understand.py produced (understanding, transcript) plus the product fields.
  1. fetch the Kaiyros hook pack for the product (opening lines of the best-selling videos
     for that same product; read-only)                         -> media/<id>/hook_pack.json
  2. Claude writes 3 short takes she says + 2 spare hooks               -> media/<id>/script_v2.json

Prints one JSON object: {"video_id", "ok", "script" | "error", "market_hooks"}. Always exits 0.
"""
import base64
import json
import os
import re
import sys
import urllib.error
import urllib.parse
import urllib.request
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
sys.path.insert(0, str(HERE.parent.parent / "discover-download"))
from understand import MEDIA, ask_claude, fail  # noqa: E402

MODEL = os.environ.get("SCRIPT_MODEL", "opus")

PROMPT = """You write short TikTok Shop scripts for an AI-generated UGC creator: a friendly woman in her 20s who talks to her phone camera at home. The finished video is split-screen: the real product video plays silently on top, she talks underneath and sometimes points up at it. She never holds the product.

Her clips are generated by an AI video model that also makes her voice. It says short, plain sentences correctly and garbles long or unusual ones, so the script is cut into separate short takes, each generated on its own.

PRODUCT
{product}

A VIDEO THAT ALREADY SOLD THIS PRODUCT (our analysis of it; this is the footage that plays on top)
{understanding}

What was said in it:
{transcript}

OPENING LINES OF THE BEST-PERFORMING VIDEOS FOR THIS SAME PRODUCT (from Kaiyros, with views)
{hooks}

Write our video as exactly 3 takes: take 1 is the hook, take 2 is the reason to want it (pointing at what the top video shows), take 3 is price or proof plus where to buy.

Rules for every take:
- 15 to 18 words, one or two short sentences, said quickly in about 5.5 seconds.
- Everyday words only, each easy to pronounce. No brand names, no ingredient or technical names, no words a text-to-speech voice could trip on. Say the product type in plain words ("this neck pillow"), never the listing title.
- Numbers: at most one number per take, a whole number, spelled out in words ("thirty-four dollars", "two hundred thousand"). No decimals, no percentages.
- First person, casual, like telling a friend. No hype words like "game changer" or "obsessed".
- Keep what made the winner work (hook pattern, selling angle) but write completely fresh words; never reuse a sentence from the transcript or the opening lines.
- Only claim what the product facts or the analysis support. No medical or cure claims, no invented results, reviews, numbers or discounts. Price only if given above.
- Take 3 ends with where to buy, e.g. "the link is right there".

How to write "does" (her performance direction for that take):
- The camera sees verbs, not feelings. Never write energetic, excited, confident, charismatic, playful or any other mood word. Write the physical action instead.
- Two or three small actions, each tied to specific words of her line: "On the words <two or three words from the line> she ...". One action about every two seconds.
- Use these channels: one eyebrow lift that settles, a slight head tilt, a glance away and straight back to the lens, a small lean in, a half-beat pause, one small hand gesture at chest height with hands staying below her chin, a point straight up at the video above her (take 2), one corner of her mouth lifting, a slow nod.
- She sits on the arm of her couch and never holds the product. Hands are empty.
- End every take with: "After her last word she closes her lips and holds the lens."

Answer with ONLY one JSON object, no markdown fence, with exactly these keys:
{{
 "remake_fit": {{"score": 1-10, "reason": "one sentence: how well this works as her talking under the product video"}},
 "concept": "one sentence: the idea of our video",
 "takes": [{{"n": 1, "says": "her exact words", "job": "hook | reason | buy", "does": "what she physically does while saying it"}}],
 "other_hooks": [{{"says": "an alternative take 1, same rules", "pattern": "e.g. curiosity gap, problem, deal", "inspired_by": "which opening line id, or 'the analysed video'"}}],
 "hook_pattern": "pattern used in take 1 and what inspired it",
 "overlay_caption": "2-4 word caption burned onto the video, no emoji",
 "caption": "post caption with 3-5 hashtags",
 "claims_left_out": "claims from the original we deliberately did not repeat, or null"
}}
Give exactly 3 takes and exactly 2 other_hooks."""


def hook_pack(product_id, folder):
    """Market opening lines for this product from Kaiyros. [] when it has none or the call fails."""
    cache = folder / "hook_pack.json"
    if cache.exists():
        return json.loads(cache.read_text())
    import discover
    token = discover.id_token()
    account = json.loads(discover.SESSION.read_text()).get("account_id")
    url = f"{discover.LIVE_API}/v1/creator-lab/hook-pack?" + urllib.parse.urlencode({"product": f"catalog:{product_id}"})
    headers = {"Authorization": f"Bearer {token}", "Accept": "application/json"}
    if account:
        headers["X-Kaiyros-Account"] = account
    try:
        with urllib.request.urlopen(urllib.request.Request(url, headers=headers), timeout=60) as r:
            data = json.load(r)["data"]
    except (urllib.error.URLError, ValueError, KeyError):
        return []
    hooks = []
    for ex in (data.get("market") or {}).get("examples") or []:
        o = ex.get("opening") or {}
        said = (o.get("said") or {}).get("text")
        screen = (o.get("on_screen") or {}).get("text")
        if said or screen:
            hooks.append({"id": ex.get("id"), "views": ex.get("views"), "creator": ex.get("creator_handle"),
                          "said": said, "on_screen": screen, "hook_type": o.get("hook_type")})
    cache.write_text(json.dumps(hooks, indent=2))
    return hooks


def main():
    if len(sys.argv) == 3 and sys.argv[1] == "--json":
        item = json.loads(sys.argv[2])
    elif len(sys.argv) == 2:
        item = json.loads(base64.b64decode(sys.argv[1]))
    else:
        sys.exit(__doc__)
    vid = str(item.get("video_id") or "")
    if not re.fullmatch(r"\d{5,25}", vid):
        fail(vid, "bad video_id")
    if not item.get("understanding"):
        fail(vid, "video was not understood, so no script")
    folder = MEDIA / vid
    folder.mkdir(parents=True, exist_ok=True)
    out = folder / "script_v2.json"
    try:
        hooks = []
        if re.fullmatch(r"\d{5,25}", str(item.get("product_id") or "")):
            try:
                hooks = hook_pack(item["product_id"], folder)
            except SystemExit:  # discover.py exits when the Kaiyros session is missing or expired
                hooks = []
        if out.exists():
            script = json.loads(out.read_text())
        else:
            facts = [f"Name: {item.get('product_title') or 'unknown'}"]
            if item.get("product_price"):
                facts.append(f"Price: ${item['product_price']}")
            if item.get("product_sold") is not None:
                facts.append(f"Units sold: {item['product_sold']}")
            if item.get("product_rating"):
                facts.append(f"Rating: {item['product_rating']} stars")
            lines = "\n".join(
                f"- {h['id']} ({h['views']:,} views{', ' + h['hook_type'] if h.get('hook_type') else ''}): "
                f"said: {h['said'] or '-'} | on screen: {h['on_screen'] or '-'}" for h in hooks)
            script = ask_claude(PROMPT.format(
                product="\n".join(facts), understanding=json.dumps(item["understanding"], indent=1),
                transcript=(item.get("transcript") or "(no speech)")[:4000],
                hooks=lines or "(Kaiyros has none for this product)"), folder, MODEL)
            out.write_text(json.dumps(script, indent=2))
    except (RuntimeError, ValueError, OSError) as e:
        fail(vid, str(e)[:400])
    print(json.dumps({"video_id": vid, "ok": True, "script": script, "market_hooks": hooks}))


if __name__ == "__main__":
    main()
